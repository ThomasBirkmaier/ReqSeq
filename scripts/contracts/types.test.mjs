import { describe, expect, it } from "vitest";
import { loadContracts } from "./load.mjs";
import { generateTypes } from "./types.mjs";

const meta = { type: "object", properties: { commands: { type: "array" } }, additionalProperties: false };
const command = (name, input, output = { type: "object", additionalProperties: false }) => ({
  name,
  summary: `Test command ${name}.`,
  input,
  output,
});
const generate = ({ schemas = {}, commands = [], renames = {} } = {}) =>
  generateTypes({ schemas, meta, catalog: { commands } }, { renames });
/** The declaration of one type, up to the blank line that separates declarations. */
const declaration = (source, name) => {
  const start = source.search(new RegExp(`export (?:interface|type) ${name}\\b`));
  if (start === -1) {
    throw new Error(`no declaration of ${name}`);
  }
  const end = source.indexOf("\n\n", start);
  return source.slice(start, end === -1 ? undefined : end + 1);
};

describe("generated TypeScript types", () => {
  it("names common $defs as they are, other $defs and file roots after their file", () => {
    const out = generate({
      schemas: {
        "common.schema.json": { $defs: { shortId: { type: "string" } } },
        "data-export.schema.json": {
          type: "object",
          properties: { id: { $ref: "common.schema.json#/$defs/shortId" } },
          additionalProperties: false,
          $defs: { element: { $ref: "#" } },
        },
      },
      commands: [command("element.setStatus", { $ref: "../data-export.schema.json#/$defs/element" })],
    });
    expect(out).toContain("export type ShortId = string;");
    expect(out).toContain("export interface DataExportFile {\n  readonly id?: ShortId;\n}");
    expect(out).toContain("export type DataExportElement = DataExportFile;");
    expect(out).toContain("export type ElementSetStatusInput = DataExportElement;");
    expect(out).toContain("export type ElementSetStatusOutput = Readonly<Record<string, never>>;");
    expect(out).toContain(
      '  readonly "element.setStatus": { readonly input: ElementSetStatusInput; readonly output: ElementSetStatusOutput };',
    );
    expect(out).toContain("export interface CatalogMeta {");
    expect(out).not.toContain("CommonFile");
    expect(out.startsWith("// Generated by scripts/contracts/generate.mjs")).toBe(true);
  });

  it("maps types, const, enum and nullable types", () => {
    const out = generate({
      schemas: {
        "x.schema.json": {
          type: "object",
          required: ["a", "b", "c", "d", "e", "f"],
          properties: {
            a: { type: "integer", minimum: 1 },
            b: { const: 1 },
            c: { enum: ["x", 2, true, null] },
            d: { type: ["string", "null"], format: "date-time" },
            e: { type: "array", items: { type: ["string", "number"] } },
            f: { type: "array" },
            g: { description: "Never written.", not: {} },
            h: true,
            i: false,
            "j-k": { type: "boolean" },
          },
          additionalProperties: false,
        },
      },
    });
    expect(declaration(out, "XFile")).toBe(
      [
        "export interface XFile {",
        "  readonly a: number;",
        "  readonly b: 1;",
        '  readonly c: "x" | 2 | true | null;',
        "  readonly d: string | null;",
        "  readonly e: readonly (string | number)[];",
        "  readonly f: readonly unknown[];",
        "  /** Never written. */",
        "  readonly g?: never;",
        "  readonly h?: unknown;",
        "  readonly i?: never;",
        '  readonly "j-k"?: boolean;',
        "}\n",
      ].join("\n"),
    );
  });

  it("gives open objects an index signature and closed empty objects Record<string, never>", () => {
    const out = generate({
      schemas: {
        "x.schema.json": {
          $defs: {
            open: { type: "object", properties: { a: { type: "string" } } },
            map: { type: "object", additionalProperties: { type: "integer" } },
            mixed: {
              type: "object",
              properties: { a: { type: "string" } },
              additionalProperties: { type: "integer" },
            },
            any: { type: "object" },
            empty: { type: "object", properties: {}, additionalProperties: false },
            extra: { type: "object", required: ["z"], additionalProperties: false },
            extraOpen: { type: "object", required: ["z"] },
            extraTyped: { type: "object", required: ["z"], additionalProperties: { type: "boolean" } },
          },
        },
      },
    });
    expect(declaration(out, "XOpen")).toContain(
      "  readonly a?: string;\n  readonly [key: string]: unknown;\n}",
    );
    expect(out).toContain("export type XMap = Readonly<Record<string, number>>;");
    expect(declaration(out, "XMixed")).toContain("  readonly [key: string]: number | string;\n}");
    expect(out).toContain("export type XAny = Readonly<Record<string, unknown>>;");
    expect(out).toContain("export type XEmpty = Readonly<Record<string, never>>;");
    // A required property that `properties` does not list has the type of the other properties.
    expect(declaration(out, "XExtra")).toContain("  readonly z: never;\n}");
    expect(declaration(out, "XExtraOpen")).toContain(
      "  readonly z: unknown;\n  readonly [key: string]: unknown;\n}",
    );
    expect(declaration(out, "XExtraTyped")).toContain(
      "  readonly z: boolean;\n  readonly [key: string]: boolean;\n}",
    );
  });

  it("simplifies unions the way the type checker sees them", () => {
    const out = generate({
      schemas: {
        "common.schema.json": {
          $defs: {
            uuid: { type: "string" },
            shortId: { type: "string" },
            elementRef: { anyOf: [{ $ref: "#/$defs/uuid" }, { $ref: "#/$defs/shortId" }] },
            view: { anyOf: [{ const: "core" }, { $ref: "#/$defs/elementRef" }] },
            sortBy: { anyOf: [{ enum: ["id", "title"] }, { $ref: "#/$defs/uuid" }] },
            anything: { anyOf: [{ type: "string" }, {}] },
            twice: { oneOf: [{ type: "string" }, { type: "string" }, { type: "boolean" }] },
            nothing: { anyOf: [false] },
            obj: { type: "object", properties: { a: { type: "number" } }, additionalProperties: false },
            sameObject: { anyOf: [{ $ref: "#/$defs/obj" }, { $ref: "#/$defs/obj" }, { type: "null" }] },
            sameLiteral: { enum: ["a", "a", "b"] },
            long: {
              enum: [
                "aaaaaaaaaaaaaaaa",
                "bbbbbbbbbbbbbbbbbbbb",
                "cccccccccccccccccccc",
                "dddddddddddddddddddd",
              ],
            },
          },
        },
      },
    });
    expect(out).toContain("export type ElementRef = string;");
    expect(out).toContain("export type View = ElementRef;");
    expect(out).toContain("export type SortBy = Uuid;");
    expect(out).toContain("export type Anything = unknown;");
    expect(out).toContain("export type Twice = string | boolean;");
    expect(out).toContain("export type Nothing = never;");
    expect(out).toContain("export type SameObject = Obj | null;");
    expect(out).toContain('export type SameLiteral = "a" | "b";');
    expect(out).toContain(
      'export type Long =\n  | "aaaaaaaaaaaaaaaa"\n  | "bbbbbbbbbbbbbbbbbbbb"\n  | "cccccccccccccccccccc"\n  | "dddddddddddddddddddd";',
    );
  });

  it("intersects allOf and merges it into one closed object with unevaluatedProperties: false", () => {
    const out = generate({
      schemas: {
        "m.schema.json": {
          $defs: {
            named: {
              type: "object",
              required: ["key"],
              properties: { key: { type: "string" }, name: { type: "string" } },
            },
            type: {
              allOf: [{ $ref: "#/$defs/named" }],
              required: ["prefix"],
              properties: { key: true, name: true, prefix: { type: "string" } },
              unevaluatedProperties: false,
            },
            both: {
              allOf: [{ $ref: "#/$defs/named" }, { type: "object", properties: { x: { type: "number" } } }],
            },
            keyNotId: { allOf: [{ type: "string" }, { not: { enum: ["id"] } }] },
            onlyNamed: { allOf: [{ $ref: "#/$defs/named" }], unevaluatedProperties: false },
            typeOrOmit: {
              type: "object",
              properties: { type: { type: "string" }, omit: { const: true } },
              oneOf: [{ required: ["type"] }, { required: ["omit"] }],
              additionalProperties: false,
            },
          },
        },
      },
    });
    expect(declaration(out, "MType")).toBe(
      "export interface MType {\n  readonly key: string;\n  readonly name?: string;\n  readonly prefix: string;\n}\n",
    );
    expect(out).toMatch(
      /export type MBoth = MNamed & \{\n {2}readonly x\?: number;\n {2}readonly \[key: string\]: unknown;\n\};/,
    );
    expect(out).toContain("export type MKeyNotId = string;");
    // Without own properties, too: closed, no index signature of `named`.
    expect(declaration(out, "MOnlyNamed")).toBe(
      "export interface MOnlyNamed {\n  readonly key: string;\n  readonly name?: string;\n}\n",
    );
    expect(out).toContain(
      "export type MTypeOrOmit = {\n  readonly type?: string;\n  readonly omit?: true;\n} & (\n  | {\n    readonly type: unknown;\n  }\n  | {\n    readonly omit: unknown;\n  });",
    );
  });

  it("makes input properties with a default required, also through $ref, but not below oneOf or in outputs", () => {
    const withDefaults = {
      type: "object",
      properties: {
        limit: { type: "integer", default: 50 },
        nested: {
          type: "object",
          properties: { order: { enum: ["asc", "desc"], default: "asc" } },
          additionalProperties: false,
        },
        choice: { oneOf: [{ type: "object", properties: { deep: { type: "boolean", default: false } } }] },
        shared: { $ref: "../x.schema.json#/$defs/sort" },
        list: { type: "array", items: { $ref: "../x.schema.json#/$defs/sorted" } },
        merged: { $ref: "../x.schema.json#/$defs/merged" },
        plain: { $ref: "../x.schema.json#/$defs/plain" },
        either: { anyOf: [{ $ref: "../x.schema.json#/$defs/sort" }, { type: "null" }] },
      },
      additionalProperties: false,
    };
    const out = generate({
      schemas: {
        "x.schema.json": {
          $defs: {
            sort: {
              type: "object",
              properties: { by: { type: "string", default: "id" } },
              additionalProperties: false,
            },
            // Reaches the default only through a $ref of its own (and refers to itself).
            sorted: {
              type: "object",
              properties: { key: { $ref: "#/$defs/sort" }, next: { $ref: "#/$defs/sorted" } },
              additionalProperties: false,
            },
            merged: {
              allOf: [{ $ref: "#/$defs/sortPart" }],
              properties: { by: true, x: { type: "string" } },
              unevaluatedProperties: false,
            },
            sortPart: { type: "object", properties: { by: { type: "string", default: "id" } } },
            plain: { type: "object", properties: { y: { type: "string" } }, additionalProperties: false },
          },
        },
      },
      commands: [command("element.list", withDefaults, withDefaults)],
    });
    const input = declaration(out, "ElementListInput");
    expect(input).toContain("  readonly limit: number;");
    expect(input).toContain('    readonly order: "asc" | "desc";');
    expect(input).toContain("    readonly deep?: boolean;");
    // Ajv fills defaults through $ref too: input refers to the variant with the default required.
    expect(input).toContain("  readonly shared?: XSortWithDefaults;");
    expect(input).toContain("  readonly list?: readonly XSortedWithDefaults[];");
    expect(input).toContain("  readonly merged?: XMergedWithDefaults;");
    expect(input).toContain("  readonly plain?: XPlain;");
    expect(input).toContain("  readonly either?: XSort | null;");
    expect(declaration(out, "XSort")).toContain("  readonly by?: string;");
    expect(declaration(out, "XSortWithDefaults")).toContain("  readonly by: string;");
    expect(declaration(out, "XSortedWithDefaults")).toContain(
      "  readonly key?: XSortWithDefaults;\n  readonly next?: XSortedWithDefaults;",
    );
    expect(declaration(out, "XMergedWithDefaults")).toContain(
      "  readonly by: string;\n  readonly x?: string;",
    );
    expect(out).not.toContain("XPlainWithDefaults");
    const output = declaration(out, "ElementListOutput");
    expect(output).toContain("  readonly limit?: number;");
    expect(output).toContain("  readonly shared?: XSort;");
  });

  it("keeps descriptions as doc comments, one line each", () => {
    const out = generate({
      schemas: {
        "x.schema.json": {
          $defs: {
            a: {
              description: "First line\n  second */ line.",
              type: "object",
              properties: { p: { type: "string", description: "P." } },
            },
          },
        },
      },
    });
    expect(out).toContain(
      "/**\n * First line second *\\/ line.\n * Schema: `schemas/x.schema.json#/$defs/a`.\n */\nexport interface XA {\n  /** P. */\n",
    );
  });

  it("refuses what it cannot type: unknown keywords, refs, names", () => {
    const one = (def) => () => generate({ schemas: { "x.schema.json": { $defs: { a: def } } } });
    expect(one({ type: "object", patternProperties: {} })).toThrow(
      "x.schema.json#/$defs/a: keyword patternProperties is not supported",
    );
    expect(one({ $ref: "#/properties/a" })).toThrow("x.schema.json: unsupported $ref #/properties/a");
    expect(one({ $ref: "y.schema.json" })).toThrow("x.schema.json: $ref y.schema.json points to nothing");
    expect(one({ type: "date" })).toThrow("x.schema.json#/$defs/a: unknown type date");
    expect(
      one({
        allOf: [{ anyOf: [{ type: "object" }] }],
        properties: { a: true },
        unevaluatedProperties: false,
      }),
    ).toThrow("allOf with unevaluatedProperties needs plain object schemas");
    expect(
      one({
        allOf: [{ type: "object", properties: { b: { type: "string" } }, additionalProperties: false }],
        properties: { a: { type: "string" } },
        unevaluatedProperties: false,
      }),
    ).toThrow("allOf with unevaluatedProperties needs plain object schemas");
    expect(one({ allOf: [{ type: "object" }], oneOf: [{}], unevaluatedProperties: false })).toThrow(
      "x.schema.json#/$defs/a: allOf with unevaluatedProperties and oneOf is not supported",
    );
    expect(one({ const: { a: 1 } })).toThrow(
      "x.schema.json#/$defs/a: const or enum with an object or array value is not supported",
    );
    expect(one({ enum: ["a", ["b"]] })).toThrow(
      "const or enum with an object or array value is not supported",
    );
    expect(() =>
      generate({ schemas: { "common.schema.json": { $defs: { selection: { type: "object" } } } } }),
    ).toThrow("generated type name Selection is a global name; add a rename");
    expect(() =>
      generate({ schemas: { "common.schema.json": { $defs: { error: { type: "string" } } } } }),
    ).toThrow("generated type name Error is a global name; add a rename");
    expect(() =>
      generate({
        schemas: { "x.schema.json": { $defs: { a: { type: "string" } } } },
        renames: { "y#": "Y" },
      }),
    ).toThrow("rename of y#: no such schema");
    expect(() =>
      generate({
        schemas: { "element.schema.json": { $defs: { getInput: { type: "string" } } } },
        commands: [command("element.get", { type: "object" })],
      }),
    ).toThrow(
      "element.get input: generated type name ElementGetInput is also used by element.schema.json#/$defs/getInput",
    );
  });

  it("types the real schemas and catalog the same way on every run", () => {
    const { schemas, meta: realMeta, catalog } = loadContracts();
    const first = generateTypes({ schemas, meta: realMeta, catalog });
    expect(generateTypes({ schemas, meta: realMeta, catalog })).toBe(first);
    expect(first).toContain("export interface CommandErrorObject {");
    expect(first).toContain("export interface CommandCatalog {");
    expect(first).toContain("export type IsoDateTime = string;");
    for (const cmd of catalog.commands) {
      expect(first).toContain(`  readonly ${JSON.stringify(cmd.name)}: { readonly input: `);
    }
  });
});
