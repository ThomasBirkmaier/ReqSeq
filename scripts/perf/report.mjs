// Turns the measurements of the performance suite (`pnpm test:perf`, JSON lines in
// test-results/perf.jsonl, see packages/testkit/src/perf.ts) into the analysis record
// verification/performance.md (ADR-0011, D-050). CI runners are not the reference machine, so a
// time over its threshold is reported, not failed: the workflow opens an issue (.github/workflows/perf.yml).
//
// Usage: node scripts/perf/report.mjs --results test-results/perf.jsonl --out verification/performance.md
//        [--commit <sha>] [--run-url <url>] [--summary <file>] [--github-output <file>]
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";

/** The measurements of a results file, one JSON object per non-empty line. */
export function parseResults(text) {
  return text
    .split("\n")
    .filter((line) => line.trim() !== "")
    .map((line, i) => {
      const value = JSON.parse(line);
      if (
        typeof value?.name !== "string" ||
        typeof value.basis !== "string" ||
        typeof value.ms !== "number"
      ) {
        throw new Error(`line ${i + 1}: not a measurement: ${line}`);
      }
      return value;
    });
}

/** Measurements whose time is over their threshold. */
export const exceeded = (measurements) =>
  measurements.filter((m) => m.thresholdMs !== undefined && m.ms > m.thresholdMs);

const seconds = (ms) => `${(ms / 1000).toFixed(1)} s`;

/** The machine the run measured on. */
export const machineOf = () => ({
  os: `${os.type()} ${os.release()} (${os.arch()})`,
  cores: os.cpus().length,
  memoryGb: Math.round(os.totalmem() / 1024 ** 3),
  node: process.version,
});

/** The record as Markdown. */
export function renderReport({ measurements, machine, commit, runUrl, date }) {
  const over = exceeded(measurements);
  const rows = measurements.map((m) => {
    const result =
      m.thresholdMs === undefined ? "no threshold" : m.ms > m.thresholdMs ? "**exceeded**" : "within";
    const threshold = m.thresholdMs === undefined ? "" : seconds(m.thresholdMs);
    return `| ${m.name} | ${m.basis} | ${seconds(m.ms)} | ${threshold} | ${result} |`;
  });
  return [
    "# Performance with 50,000 elements and 200,000 relations (N-036)",
    "",
    "Verification method: Analyse. Record written by the performance job (`scripts/perf/report.mjs`, ADR-0011, #126). **Not confirmed.** A human confirms it at stage acceptance (D-050).",
    "",
    "Workspace: generated by `generateLargeWorkspace` of `packages/testkit` (D-055) with seed 36: 50,000 elements of the standard model (needs, use cases, decisions, variants, packages, system requirements) in four repositories, 200,000 relation targets with valid versions. Tests: `packages/*/test/perf/` (`pnpm test:perf`).",
    "",
    'The machine below is not the reference machine of N-036 and SR-082 (4 cores, 16 GB, SSD), so the times are an indication. A time over its threshold opens an issue labelled `perf`, not a red build (ADR-0011). "Cold" means without the LogReq cache; the files were just written, so the operating system has them in its page cache.',
    "",
    `- Date: ${date}`,
    `- Commit: ${commit ?? "unknown"}`,
    ...(runUrl === undefined ? [] : [`- Run: ${runUrl}`]),
    `- Machine: ${machine.os}, ${machine.cores} cores, ${machine.memoryGb} GB, Node ${machine.node}`,
    "",
    "| Measurement | Basis | Time | Threshold | Result |",
    "|---|---|---|---|---|",
    ...rows,
    "",
    over.length === 0
      ? "Result: every measured time is within its threshold."
      : `Result: ${over.length} of ${measurements.length} measurements over their threshold: ${over.map((m) => m.name).join("; ")}.`,
    "",
  ].join("\n");
}

const option = (args, name) => {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
};

/** Runs the command line; returns the number of exceeded thresholds. */
export function main(args, now = new Date()) {
  const results = option(args, "--results") ?? "test-results/perf.jsonl";
  const out = option(args, "--out") ?? "verification/performance.md";
  const measurements = parseResults(fs.readFileSync(results, "utf8"));
  if (measurements.length === 0) {
    throw new Error(`${results} has no measurements`);
  }
  const report = renderReport({
    measurements,
    machine: machineOf(),
    commit: option(args, "--commit"),
    runUrl: option(args, "--run-url"),
    date: now.toISOString().slice(0, 10),
  });
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, report);
  const summary = option(args, "--summary");
  if (summary !== undefined) {
    fs.appendFileSync(summary, report);
  }
  const over = exceeded(measurements);
  const output = option(args, "--github-output");
  if (output !== undefined) {
    fs.appendFileSync(output, `exceeded=${over.length}\n`);
  }
  console.log(`wrote ${out}: ${measurements.length} measurements, ${over.length} over their threshold`);
  return over.length;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}
