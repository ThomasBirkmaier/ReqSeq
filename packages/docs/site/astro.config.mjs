// The user documentation site (ADR-0017). Nothing here loads from the network: no web fonts, no CDN, no analytics.
import { existsSync } from "node:fs";
import { URL } from "node:url";
import starlight from "@astrojs/starlight";
import { defineConfig, passthroughImageService } from "astro/config";
import starlightLinksValidator from "starlight-links-validator";

// The sections of the hand-written pages (D-067), each a folder of docs/guide/. packages/docs/src/assemble.ts
// (GUIDE_SECTIONS) refuses a page outside them and index.md, so no page is left out of the sidebar.
const GUIDE_SECTIONS = [
  ["start", "Get started"],
  ["how-to", "How-to"],
  ["concepts", "Concepts"],
];

export default defineConfig({
  site: "https://thomasbirkmaier.github.io",
  // `/ReqSeq` for GitHub Pages; the offline build that ships with a delivery sets `/` (SR-141, ADR-0017).
  base: process.env.REQSEQ_DOCS_BASE ?? "/ReqSeq",
  // The screenshots of docs/guide/images/ are served as they are: Astro's default service needs Sharp, a native
  // package that the site's install (--ignore-scripts) does not build. A missing image still fails the build.
  image: { service: passthroughImageService() },
  integrations: [
    starlight({
      title: "ReqSeq",
      description: "User documentation of ReqSeq.",
      customCss: ["./src/styles/theme.css"],
      sidebar: [
        { label: "Overview", slug: "index" },
        // A section without pages yet is left out rather than shown empty.
        ...GUIDE_SECTIONS.filter(([directory]) =>
          existsSync(new URL(`src/content/docs/${directory}`, import.meta.url)),
        ).map(([directory, label]) => ({ label, items: [{ autogenerate: { directory } }] })),
        // Generated by packages/docs/src (SR-139); the index page and then the commands in catalog order.
        { label: "Commands", items: [{ autogenerate: { directory: "reference/commands" } }] },
        { label: "Problem and error codes", slug: "reference/problem-codes" },
        { label: "File formats", items: [{ autogenerate: { directory: "reference/formats" } }] },
        { label: "Common types", slug: "reference/common-types" },
        { label: "Standard model", slug: "reference/standard-model" },
      ],
      // A dead internal link fails the build.
      plugins: [starlightLinksValidator()],
    }),
  ],
});
